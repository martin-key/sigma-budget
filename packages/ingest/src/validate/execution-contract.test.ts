import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { canonical, CONTRACT, money, moneyDecimal, numbers } from './execution-contract.js';
import { Check, isnum, numbersIn, pattern, walk } from './checks.js';
import { runGroups } from './runner.js';

const fixture = new URL('../../test/fixtures/validate14/', import.meta.url);
const load = (name: string): any => JSON.parse(readFileSync(new URL(name, fixture), 'utf8'));
const oracle = load('oracle.json');

describe('frozen Python execution contract', () => {
  it('preserves the published contract and numeric projection', () => {
    const input = load('execution.json');
    expect(CONTRACT).toEqual(load('contract.json'));
    expect(numbers(input)).toEqual(oracle.numbers);
    expect(input).toEqual(load('execution.json'));
  });
  it('matches the canonical projection independently generated by Python', () => {
    expect(canonical(oracle.numbers)).toEqual(oracle.canonical);
  });
  it('rounds decimal ties away from zero and normalizes negative zero', () => {
    for (const row of oracle.money) expect(moneyDecimal(row.input, row.places)).toBe(row.value);
  });
  it('maps independent edge-case projections and rejects malformed numeric inputs', () => {
    const input = load('synthetic-execution.json');
    expect(canonical(input)).toEqual(oracle.syntheticCanonical);
    expect(numbers(oracle.syntheticCanonical)).toEqual(oracle.syntheticNumbers);
    for (const row of oracle.moneyValues) {
      if (row.expected.ok) expect(money(row.input, row.places)).toEqual(row.expected.value);
      else expect(() => money(row.input, row.places)).toThrow();
    }
  });
  it('leaves v1 values unchanged', () => {
    const old = { schema: 1 };
    expect(numbers(old)).toBe(old);
  });
});

describe('collector and explicit group runner', () => {
  it('counts checks while keeping warnings and facts separate', () => {
    const c = new Check('X');
    c.ok(true, 'ok');
    c.near(1, 1.1, 0.1, 'near');
    c.fail('bad');
    c.warn('warning');
    c.fact('fact');
    expect({ n: c.n, problems: c.problems, warnings: c.warnings, facts: c.facts }).toEqual({
      n: 3,
      problems: ['bad'],
      warnings: ['warning'],
      facts: ['fact'],
    });
  });
  it('rejects unknown groups and converts crashes into failures', () => {
    const groups = [
      {
        name: 'A',
        description: '',
        run: () => {
          throw new Error('broken');
        },
      },
    ];
    expect(() => runGroups(groups, {}, ['CORE'])).toThrow('unknown or unported');
    expect(() => runGroups(groups, {}, [])).toThrow('Explicit');
    expect(runGroups(groups, {}, ['A']).groups[0]?.problems).toEqual([
      'group crashed: Error: broken',
    ]);
  });
  it('orders registered groups like the donor and leaves extensions stable', () => {
    const group = (name: string) => ({ name, description: '', run: () => new Check(name) });
    const result = runGroups(
      [group('EXTRA1'), group('GLOSSARY'), group('INPUTS'), group('EXTRA2')],
      {},
      ['GLOSSARY', 'INPUTS', 'EXTRA1', 'EXTRA2'],
    );
    expect(result.groups.map((c) => c.name)).toEqual(['INPUTS', 'GLOSSARY', 'EXTRA1', 'EXTRA2']);
  });
  it('walks paths and excludes booleans and nonfinite numbers', () => {
    expect([...walk({ a: [1, true, Infinity] })].map(([p]) => p)).toEqual([
      '$',
      '$.a',
      '$.a[0]',
      '$.a[1]',
      '$.a[2]',
    ]);
    expect(pattern('$.a[12].b[1]')).toBe('$.a[].b[]');
    expect(numbersIn({ a: [1, true, Infinity, null] })).toBe(1);
    expect(isnum(NaN)).toBe(false);
  });
});
